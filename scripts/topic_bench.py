#!/usr/bin/env python3
"""Measure a ROS 2 topic's real rate, jitter and payload bandwidth.

Added in this fork. Unlike `ros2 topic hz`/`ros2 topic bw`, this prints a single
machine-readable row (CSV) plus a markdown row, so numbers quoted in a report or a
resume can be regenerated by one command instead of being eyeballed from scrolling
terminal output.

Usage:
    ros2 topic list                       # find the topic
    python3 scripts/topic_bench.py /compressed_image_broadcaster/image/compressed --seconds 20
    python3 scripts/topic_bench.py <topic> --type sensor_msgs/msg/CompressedImage --csv out.csv

Notes:
  * Inter-arrival statistics use the local steady clock of the subscriber, so they measure
    what the subscriber actually sees (transport + executor included), not the producer's
    intent.
  * The first message is used only as a time origin and is excluded from the deltas, so a
    subscription that starts mid-stream does not report a bogus first delta.
"""
import argparse
import statistics
import sys
import time

import rclpy
from rclpy.node import Node
from rclpy.qos import QoSProfile, ReliabilityPolicy, HistoryPolicy
from rclpy.serialization import serialize_message
from rosidl_runtime_py.utilities import get_message


class Bench(Node):
    def __init__(self, topic, type_name, qos_depth, reliability):
        super().__init__('topic_bench')
        msg_type = get_message(type_name)
        qos = QoSProfile(
            depth=qos_depth,
            history=HistoryPolicy.KEEP_LAST,
            reliability=(ReliabilityPolicy.RELIABLE
                         if reliability == 'reliable'
                         else ReliabilityPolicy.BEST_EFFORT),
        )
        self.stamps = []
        self.bytes = []
        self.first_payload = 0
        self.create_subscription(msg_type, topic, self.on_msg, qos)

    def on_msg(self, msg):
        self.stamps.append(time.monotonic())
        size = len(serialize_message(msg))
        self.bytes.append(size)
        if not self.first_payload:
            self.first_payload = size


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('topic')
    ap.add_argument('--type', default='sensor_msgs/msg/CompressedImage')
    ap.add_argument('--seconds', type=float, default=20.0)
    ap.add_argument('--qos-depth', type=int, default=10)
    ap.add_argument('--qos-reliability', choices=['best_effort', 'reliable'],
                    default='best_effort')
    ap.add_argument('--csv', default='')
    args = ap.parse_args()

    rclpy.init()
    node = Bench(args.topic, args.type, args.qos_depth, args.qos_reliability)

    # Spin until a publisher shows up, so a bench started before the producer is still valid.
    deadline = time.monotonic() + 30.0
    while node.count_publishers(args.topic) == 0:
        if time.monotonic() > deadline:
            print(f'ERROR: no publisher on {args.topic} after 30 s', file=sys.stderr)
            node.destroy_node()
            rclpy.shutdown()
            return 2
        rclpy.spin_once(node, timeout_sec=0.1)

    end = time.monotonic() + args.seconds
    while time.monotonic() < end:
        rclpy.spin_once(node, timeout_sec=0.05)

    n = len(node.stamps)
    if n < 2:
        print(f'ERROR: only {n} message(s) received in {args.seconds} s', file=sys.stderr)
        node.destroy_node()
        rclpy.shutdown()
        return 3

    deltas = [b - a for a, b in zip(node.stamps, node.stamps[1:])]
    span = node.stamps[-1] - node.stamps[0]
    hz = (n - 1) / span if span > 0 else 0.0
    mean_dt = statistics.fmean(deltas)
    std_dt = statistics.pstdev(deltas) if len(deltas) > 1 else 0.0
    total_bytes = sum(node.bytes[1:])

    print(f'# topic={args.topic} type={args.type} qos={args.qos_reliability}')
    print(f'messages={n} window={span:.3f}s hz={hz:.3f} '
          f'dt_mean={mean_dt * 1e3:.2f}ms dt_min={min(deltas) * 1e3:.2f}ms '
          f'dt_max={max(deltas) * 1e3:.2f}ms dt_std={std_dt * 1e3:.2f}ms '
          f'jitter={"%.2f" % (100.0 * std_dt / mean_dt if mean_dt else 0)}% '
          f'payload_mean={statistics.fmean(node.bytes):.0f}B '
          f'bw={total_bytes / span / 1e6:.3f}MB/s')

    if args.csv:
        header = ('topic,type,qos,messages,window_s,hz,dt_mean_ms,dt_min_ms,'
                  'dt_max_ms,dt_std_ms,jitter_pct,payload_mean_B,bw_MBps\n')
        row = (f'{args.topic},{args.type},{args.qos_reliability},{n},{span:.3f},{hz:.3f},'
               f'{mean_dt * 1e3:.2f},{min(deltas) * 1e3:.2f},{max(deltas) * 1e3:.2f},'
               f'{std_dt * 1e3:.2f},{100.0 * std_dt / mean_dt if mean_dt else 0:.2f},'
               f'{statistics.fmean(node.bytes):.0f},{total_bytes / span / 1e6:.3f}\n')
        new = not __import__('os').path.exists(args.csv)
        with open(args.csv, 'a', encoding='utf-8') as fh:
            if new:
                fh.write(header)
            fh.write(row)

    node.destroy_node()
    rclpy.shutdown()
    return 0


if __name__ == '__main__':
    sys.exit(main())
